// tools/build-skill.mjs — make the agent skill's one-file script, scripts/kar-scopeguard.mjs: kernel.mjs, then
// skillcli.mjs without its import of the kernel, then the lines that run it. The kernel inside the script is the
// gated kernel, byte for byte, so the skill an agent runs is the code the tests and the mutation gate check.
//   node tools/build-skill.mjs           write the script
//   node tools/build-skill.mjs --check   exit 1 if the script is not what the two files give (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SCRIPT = 'scripts/kar-scopeguard.mjs';
export const RUN = '\n// ---- run ----\n{\n  const r = skillRun(process.argv.slice(2), readInput);\n  if (r.out) process.stdout.write(r.out);\n  if (r.err) process.stderr.write(r.err);\n  process.exitCode = r.code;\n}\n';

export function skillScript(kernel, cli) {
  const body = cli.split('\n').filter((l) => !/^import .* from '\.\/kernel\.mjs';\s*$/.test(l)).join('\n');
  return '#!/usr/bin/env node\n'
    + '// kar-scopeguard: the agent skill script, generated by tools/build-skill.mjs in the sjgant80-hub/kar-scopeguard repository.\n'
    + '// The KERNEL part is kernel.mjs byte for byte (tested and mutation-gated there). No network, no dependencies, writes\n'
    + '// no files: it reads the diff you name and prints a JSON report. MIT licence.\n'
    + '// ---- KERNEL (kernel.mjs) ----\n' + kernel
    + '// ---- CLI (skillcli.mjs) ----\n' + body + RUN;
}

/** the skill's examples folder, from the page's examples: <id>.diff, <id>.scope, <id>.claim and the expected <id>.out.json */
export async function exampleFiles() {
  const { EXAMPLES } = await import('../examples.mjs');
  const { skillRun } = await import('../skillcli.mjs');
  const out = [];
  for (const ex of EXAMPLES) {
    // .txt endings: a skill package may only carry md, mjs, js, json and txt files
    const files = { ['examples/' + ex.id + '.diff.txt']: ex.diff };
    if (ex.scope) files['examples/' + ex.id + '.scope.txt'] = ex.scope;
    if (ex.claim) files['examples/' + ex.id + '.claim.txt'] = ex.claim;
    const argv = [ex.id + '.diff.txt', ...(ex.scope ? ['--scope', ex.id + '.scope.txt'] : []), ...(ex.claim ? ['--claim', ex.id + '.claim.txt'] : [])];
    const r = skillRun(argv, (p) => files['examples/' + p]);
    files['examples/' + ex.id + '.out.json'] = r.out;
    out.push({ id: ex.id, argv, code: r.code, files });
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = { [SCRIPT]: skillScript(readFileSync(join(root, 'kernel.mjs'), 'utf8'), readFileSync(join(root, 'skillcli.mjs'), 'utf8')) };
  for (const ex of await exampleFiles()) Object.assign(want, ex.files);
  if (process.argv.includes('--check')) {
    let bad = 0;
    for (const [p, text] of Object.entries(want)) {
      const have = existsSync(join(root, p)) ? readFileSync(join(root, p), 'utf8') : null;
      if (have !== text) { console.error(p + ' is out of date: run node tools/build-skill.mjs'); bad++; }
    }
    if (bad) process.exit(1);
    console.log(SCRIPT + ' and ' + (Object.keys(want).length - 1) + ' example files match kernel.mjs, skillcli.mjs and examples.mjs');
  } else {
    mkdirSync(join(root, 'scripts'), { recursive: true }); mkdirSync(join(root, 'examples'), { recursive: true });
    for (const [p, text] of Object.entries(want)) writeFileSync(join(root, p), text);
    console.log('wrote ' + SCRIPT + ' (' + Buffer.byteLength(want[SCRIPT]) + ' bytes) and ' + (Object.keys(want).length - 1) + ' example files');
  }
}
